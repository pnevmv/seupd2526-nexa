"""Test nGrams (ShingleFilter) on/off on top of the best pipeline:
   Standard + LowerCase + EnglishPossessive + Length + StopList + [Shingles] + KStem

Pipelines tested:
  std-stop-kstem           nGrams=off  (reference)
  std-stop-kstem-ng2       nGrams=on   shingleSize=2
  std-stop-kstem-ng3       nGrams=on   shingleSize=3

Usage:
    python3 test_ngrams_dev.py
"""

